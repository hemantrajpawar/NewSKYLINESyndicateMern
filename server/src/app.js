import "express-async-errors";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import authRoutes from "./routes/authRoutes.js";
import projectRoutes from "./routes/projectRoutes.js";
import contactRoutes from "./routes/contactRoutes.js";
import { errorHandler, notFound } from "./middleware/errorHandler.js";
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || "http://localhost:5173", credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false }), authRoutes);
app.use("/api/projects", projectRoutes);
app.use("/api/contact", rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false }), contactRoutes);
app.get("/api/health", (req, res) => res.json({ status: "ok", service: "skyline-syndicate-api", timestamp: new Date().toISOString() }));
app.get("/api/time", (req, res) => res.set("Cache-Control", "no-store").json({ now: new Date().toISOString() }));
app.use(notFound);
app.use(errorHandler);
export default app;
